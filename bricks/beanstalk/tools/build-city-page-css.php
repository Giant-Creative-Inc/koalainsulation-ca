<?php
/**
 * Build the single frontend City Page stylesheet from section source files.
 *
 * @package Koala_Beanstalk
 */

// This local CLI build tool intentionally reads and writes repository files.
// phpcs:disable WordPress.WP.AlternativeFunctions

$assets_directory       = dirname( __DIR__, 3 ) . '/wp-content/themes/bricks/beanstalk/assets';
$local_assets_directory = dirname( __DIR__, 4 ) . '/ca/app/public/wp-content/themes/bricks/beanstalk/assets';
$critical_output_file   = $assets_directory . '/city-page-critical.css';
$output_file            = $assets_directory . '/city-page.css';
$source_files           = array(
	'city-page-hero.css',
	'city-page-residential-services.css',
	'city-page-commercial-services.css',
	'city-page-why-koala.css',
	'city-page-testimonials.css',
	'city-page-faq.css',
	'city-page-final-cta.css',
);
$build_bundle           = static function ( array $bundle_sources ) use ( $assets_directory ) {
	$bundle = "/* Generated by tools/build-city-page-css.php. Edit the section source files. */\n";

	foreach ( $bundle_sources as $source_file ) {
		$source_path = $assets_directory . '/' . $source_file;
		$source_css  = file_get_contents( $source_path );

		if ( false === $source_css ) {
			fwrite( STDERR, 'Unable to read ' . $source_path . PHP_EOL );
			return false;
		}

		$bundle .= "\n/* Source: " . $source_file . " */\n" . trim( $source_css ) . "\n";
	}

	return $bundle;
};
$built_critical_bundle  = $build_bundle( array( $source_files[0] ) );
$built_bundle           = $build_bundle( array_slice( $source_files, 1 ) );

if ( false === $built_critical_bundle || false === $built_bundle ) {
	exit( 1 );
}

if ( in_array( '--check', $argv, true ) ) {
	$current_bundle          = is_readable( $output_file ) ? file_get_contents( $output_file ) : false;
	$current_critical_bundle = is_readable( $critical_output_file ) ? file_get_contents( $critical_output_file ) : false;

	if ( $built_bundle !== $current_bundle || $built_critical_bundle !== $current_critical_bundle ) {
		fwrite( STDERR, "City Page CSS bundles are stale. Run composer build:css.\n" );
		exit( 1 );
	}

	exit( 0 );
}

$watch_mode      = in_array( '--watch', $argv, true );
$sync_local      = in_array( '--sync-local', $argv, true );
$last_bundle     = null;
$bundle          = $built_bundle;
$critical_bundle = $built_critical_bundle;

if ( $watch_mode ) {
	fwrite( STDOUT, "Watching City Page section CSS files. Press Ctrl+C to stop.\n" );
}

do {
	if ( $bundle !== $last_bundle ) {
		if ( false === file_put_contents( $critical_output_file, $critical_bundle ) ) {
			fwrite( STDERR, 'Unable to write ' . $critical_output_file . PHP_EOL );
			exit( 1 );
		}

		if ( false === file_put_contents( $output_file, $bundle ) ) {
			fwrite( STDERR, 'Unable to write ' . $output_file . PHP_EOL );
			exit( 1 );
		}

		fwrite( STDOUT, null === $last_bundle ? "Built assets/city-page.css.\n" : "Rebuilt assets/city-page.css.\n" );
		$last_bundle = $bundle;

		if ( $sync_local ) {
			// phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.system_calls_passthru -- This is a local CLI development tool.
			passthru( 'composer test', $test_status );
			// phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.system_calls_passthru -- This is a local CLI development tool.
			passthru( 'composer lint', $lint_status );

			if ( 0 !== $test_status || 0 !== $lint_status ) {
				fwrite( STDERR, "CSS checks failed; the Local theme was not updated.\n" );
			} else {
				$sync_files = array_merge( $source_files, array( 'city-page-critical.css', 'city-page.css' ) );

				foreach ( $sync_files as $sync_file ) {
					$source_path       = $assets_directory . '/' . $sync_file;
					$local_source_path = $local_assets_directory . '/' . $sync_file;

					if ( ! is_dir( $local_assets_directory ) || ! copy( $source_path, $local_source_path ) ) {
						fwrite( STDERR, 'Unable to synchronize ' . $sync_file . " to the Local theme.\n" );
						exit( 1 );
					}
				}

				fwrite( STDOUT, "Tests and lint passed; City Page CSS synchronized to the Local theme.\n" );
			}
		}
	}

	if ( ! $watch_mode ) {
		break;
	}

	usleep( 250000 );
	clearstatcache();
	$critical_bundle = $build_bundle( array( $source_files[0] ) );
	$bundle          = $build_bundle( array_slice( $source_files, 1 ) );

	if ( false === $critical_bundle || false === $bundle ) {
		exit( 1 );
	}
} while ( true );
