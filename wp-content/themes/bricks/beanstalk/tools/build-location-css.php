<?php
/**
 * Build location CSS while keeping section sources editable.
 *
 * @package Koala_Beanstalk
 */

// phpcs:disable WordPress.WP.AlternativeFunctions
$assets = dirname( __DIR__ ) . '/assets/';
$groups = array(
	'critical' => array( 'header', 'location-page', 'location-hero', 'location-sidebar', 'location-estimate-shell' ),
	'deferred' => array( 'footer', 'location-partners', 'location-services', 'location-video', 'location-overview', 'location-quote-banner', 'location-features', 'location-financing', 'location-community', 'city-page-final-cta', 'location-final-cta' ),
);
foreach ( $groups as $group => $sources ) {
	$css = "/* Generated by tools/build-location-css.php. Edit section source files. */\n";
	foreach ( $sources as $source ) {
		$part = file_get_contents( $assets . $source . '.css' );
		if ( 'header' === $source ) {
			foreach ( array( 'Regular', 'Medium', 'Bold' ) as $weight ) {
				$part = str_replace( '/wp-content/uploads/2024/06/FilsonPro' . $weight . '.woff', 'location-fonts/FilsonPro' . $weight . '.woff2', $part );
			}
			foreach ( array( '500', '700' ) as $weight ) {
				$part = str_replace( '/wp-content/uploads/fonts/e742afe643c24b91cd8e4c3647e7584c/montserrat--v31-normal-' . $weight . '.woff2', 'location-fonts/Montserrat.woff2', $part );
			}
			$part = str_replace( 'format("woff")', 'format("woff2")', $part );
		}
		$css .= "\n/* Source: " . $source . ".css */\n" . $part;
	}
	$file = $assets . 'location-' . $group . '.css';
	if ( in_array( '--check', $argv, true ) ) {
		if ( ! is_file( $file ) || file_get_contents( $file ) !== $css ) {
			fwrite( STDERR, 'Stale location CSS: ' . $file . PHP_EOL );
			exit( 1 );
		}
	} else {
		file_put_contents( $file, $css );
	}
}
